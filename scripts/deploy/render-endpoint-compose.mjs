#!/usr/bin/env node

import { chmod, mkdir, rename, rm, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'

const deployRoot = process.argv[2]
const releaseDir = process.argv[3]
if (!deployRoot || !releaseDir) {
  throw new Error('Usage: render-endpoint-compose.mjs DEPLOY_ROOT RELEASE_DIR')
}

const bindAddresses = csv(
  process.env.DSH_WORK_BIND_ADDRESSES ?? process.env.DSH_WORK_BIND_ADDRESS,
  process.env.DSH_WORK_BIND_ADDRESSES ? 'DSH_WORK_BIND_ADDRESSES' : 'DSH_WORK_BIND_ADDRESS',
)
for (const address of bindAddresses) {
  if (!isPrivateIpv4(address)) throw new Error(`绑定地址必须是 RFC1918 IPv4: ${address}`)
}
if (process.env.DSH_WORK_BIND_ADDRESSES && process.env.DSH_WORK_BIND_ADDRESS) {
  if (bindAddresses[0] !== process.env.DSH_WORK_BIND_ADDRESS.trim()) {
    throw new Error('DSH_WORK_BIND_ADDRESS 必须等于 DSH_WORK_BIND_ADDRESSES 的第一项')
  }
}

const workbenchPort = port(process.env.DSH_WORK_WORKBENCH_PORT ?? '4174', 'DSH_WORK_WORKBENCH_PORT')
// 与服务端 allowedWorkbenchOriginPorts 保持一致：入口端口集合是
// {绑定端口, DSH_WORK_MOBILE_PORT}。生产把移动端端口设为 443 后，
// 域名入口（地址栏不带端口，Origin 恒为 443）即可与内网 4174 并存。
const mobilePort = port(process.env.DSH_WORK_MOBILE_PORT ?? '4175', 'DSH_WORK_MOBILE_PORT')
const workbenchOriginPorts = new Set([workbenchPort, mobilePort])
const adminPort = port(process.env.DSH_WORK_ADMIN_PORT ?? '4180', 'DSH_WORK_ADMIN_PORT')
const workbenchOrigins = origins(
  process.env.DSH_WORK_WORKBENCH_ORIGINS ?? process.env.AI_HUB_WORKBENCH_PORTAL_URL,
  process.env.DSH_WORK_WORKBENCH_ORIGINS ? 'DSH_WORK_WORKBENCH_ORIGINS' : 'AI_HUB_WORKBENCH_PORTAL_URL',
  workbenchOriginPorts,
)
const adminOrigins = origins(
  process.env.DSH_WORK_ADMIN_ORIGINS ?? process.env.AI_HUB_ADMIN_PORTAL_URL,
  process.env.DSH_WORK_ADMIN_ORIGINS ? 'DSH_WORK_ADMIN_ORIGINS' : 'AI_HUB_ADMIN_PORTAL_URL',
  new Set([adminPort]),
)

for (const address of bindAddresses) {
  requireOrigin(workbenchOrigins, address, workbenchPort, '员工端')
  requireOrigin(adminOrigins, address, adminPort, '管理端')
}

const workbenchNames = unique(workbenchOrigins.map(url => url.hostname)).join(' ')
const adminNames = unique(adminOrigins.map(url => url.hostname)).join(' ')
const mappings = bindAddresses.flatMap(address => [
  `${address}:${workbenchPort}:8443`,
  `${address}:${adminPort}:8444`,
])
const yaml = [
  '# Generated by render-endpoint-compose.mjs. Do not edit.',
  'services:',
  '  web:',
  '    ports: !override',
  ...mappings.map(mapping => `      - ${JSON.stringify(mapping)}`),
  '    environment:',
  `      DSH_WORK_WORKBENCH_SERVER_NAMES: ${JSON.stringify(workbenchNames)}`,
  `      DSH_WORK_ADMIN_SERVER_NAMES: ${JSON.stringify(adminNames)}`,
  `      DSH_WORK_HEALTHCHECK_HOST: ${JSON.stringify(bindAddresses[0])}`,
  '',
].join('\n')

const resolvedDeployRoot = resolve(deployRoot)
const target = process.argv[4]
  ? resolve(process.argv[4])
  : join(resolvedDeployRoot, 'generated', 'compose.endpoints.yaml')
const relativeTarget = relative(resolvedDeployRoot, target)
if (!relativeTarget || relativeTarget.startsWith('..') || relativeTarget.startsWith('/')) {
  throw new Error('endpoint Compose output must be a file below DEPLOY_ROOT')
}
const temporary = `${target}.new-${process.pid}`
await mkdir(dirname(target), { recursive: true, mode: 0o700 })
try {
  await writeFile(temporary, yaml, { encoding: 'utf8', mode: 0o600, flag: 'wx' })
  await rename(temporary, target)
  await chmod(target, 0o600)
} finally {
  await rm(temporary, { force: true })
}
process.stdout.write(`${target}\n`)

function csv(value, name) {
  if (!value?.trim()) throw new Error(`${name} 未配置`)
  if ([...value].some(character => {
    const code = character.charCodeAt(0)
    return code < 32 || code === 127
  })) throw new Error(`${name} 不能包含控制字符`)
  const items = value.split(',').map(item => item.trim())
  if (items.some(item => !item)) throw new Error(`${name} 不能包含空项`)
  if (new Set(items).size !== items.length) throw new Error(`${name} 不能包含重复项`)
  return items
}

function origins(value, name, expectedPorts) {
  const portList = [...expectedPorts].sort((left, right) => left - right).join('、')
  return csv(value, name).map((item) => {
    let url
    try {
      url = new URL(item)
    } catch {
      throw new Error(`${name} 包含无效 URL: ${item}`)
    }
    if (process.env.NODE_ENV === 'production' && url.protocol !== 'https:') {
      throw new Error(`生产环境的 ${name} 只允许 https`)
    }
    if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password) {
      throw new Error(`${name} 包含不允许的 Origin: ${item}`)
    }
    if (item !== item.toLowerCase() || !isAllowedHostname(url.hostname)) {
      throw new Error(`${name} 包含无效或非小写的主机名: ${item}`)
    }
    if (url.pathname !== '/' || url.search || url.hash || !expectedPorts.has(effectivePort(url))) {
      throw new Error(`${name} 必须是不含路径的端口 ${portList} 之一 Origin: ${item}`)
    }
    return url
  })
}

function requireOrigin(configuredOrigins, address, expectedPort, label) {
  if (!configuredOrigins.some(url => url.hostname === address && effectivePort(url) === expectedPort)) {
    throw new Error(`${label} Origin 缺少绑定 IP ${address}:${expectedPort}`)
  }
}

function effectivePort(url) {
  return Number(url.port || (url.protocol === 'https:' ? 443 : 80))
}

function port(value, name) {
  const parsed = Number(value)
  if (!Number.isInteger(parsed) || parsed < 1 || parsed > 65535) throw new Error(`${name} 必须是有效端口`)
  return parsed
}

function unique(values) {
  return [...new Set(values)]
}

function isPrivateIpv4(value) {
  const parts = value.split('.')
  if (parts.length !== 4 || parts.some(part => !/^\d+$/.test(part) || Number(part) > 255)) return false
  const [first, second] = parts.map(Number)
  return first === 10 || (first === 172 && second >= 16 && second <= 31) || (first === 192 && second === 168)
}

function isAllowedHostname(value) {
  if (/^\d+(?:\.\d+){3}$/.test(value)) return isPrivateIpv4(value)
  if (value.includes(':') || value.length > 253) return false
  if (process.env.NODE_ENV === 'production' && !value.includes('.')) return false
  return value.split('.').every(label => /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(label))
}
